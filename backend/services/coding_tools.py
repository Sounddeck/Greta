    async def _generate_from_template(self, template_name: str, specs: Dict[str, Any]) -> Dict[str, Any]:
        """Generate code from template"""
        template = self.code_templates[template_name]
        
        # Create temporary project
        temp_dir = Path(tempfile.mkdtemp())
        
        try:
            for file_path, content in template["files"].items():
                file_full_path = temp_dir / file_path
                file_full_path.parent.mkdir(parents=True, exist_ok=True)
                
                # Process Jinja2 template
                if isinstance(content, str) and "{{" in content:
                    template_obj = Template(content)
                    content = template_obj.render(**specs)
                
                file_full_path.write_text(content)
            
            return {
                "success": True,
                "template_used": template_name,
                "files_generated": list(template["files"].keys()),
                "project_path": str(temp_dir),
                "language": template["language"]
            }
            
        except Exception as e:
            shutil.rmtree(temp_dir, ignore_errors=True)
            raise e
    
